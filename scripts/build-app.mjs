// Bundles the Mini App client (src/miniapp/client) into a module the Worker
// serves at /app/app.js (ADR 0005), and embeds the Figtree display font the
// Worker serves at a content-hashed path (ADR 0007). Run by `npm run check` and
// the Wrangler build.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { build } from "esbuild";

const result = await build({
  entryPoints: ["src/miniapp/client/main.ts"],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  legalComments: "none",
  write: false,
});
const code = result.outputFiles[0].text;
await writeFile(
  "src/miniapp/generated/client.ts",
  `// Generated by scripts/build-app.mjs from src/miniapp/client. Do not edit.\nexport const CLIENT_JS = ${JSON.stringify(code)};\n`,
);
console.log(`Mini App client: ${code.length} bytes`);

// Figtree's Latin variable subset (SIL Open Font License), the face of the wordmark.
const font = await readFile(
  "node_modules/@fontsource-variable/figtree/files/figtree-latin-wght-normal.woff2",
);
const hash = createHash("sha256").update(font).digest("hex").slice(0, 10);
await writeFile(
  "src/miniapp/generated/font.ts",
  [
    "// Generated by scripts/build-app.mjs from @fontsource-variable/figtree (SIL Open Font License). Do not edit.",
    `export const FIGTREE_PATH = "/app/figtree-${hash}.woff2";`,
    `export const FIGTREE_WOFF2_BASE64 = ${JSON.stringify(font.toString("base64"))};`,
    "",
  ].join("\n"),
);
console.log(`Mini App font: ${font.length} bytes`);
