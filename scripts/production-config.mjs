// Writes wrangler.production.jsonc (untracked) from the shared wrangler.jsonc and
// the untracked wrangler.production.local.json, so production values stay out of
// the repository. `npm run deploy` and `npm run db:migrate:remote` run this first.
//
// The local file may set: "routes", "database_id" (the D1 database), and "vars"
// (merged over the shared vars). See wrangler.production.example.json.
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";

const LOCAL = "wrangler.production.local.json";
const OUT = "wrangler.production.jsonc";
const PLACEHOLDER = "00000000-0000-0000-0000-000000000000";

/** Removes // and /* *\/ comments outside strings, and trailing commas. */
function stripJsonc(text) {
  let out = "";
  let inString = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inString) {
      out += c;
      if (c === "\\") out += text[++i] ?? "";
      else if (c === '"') inString = false;
    } else if (c === '"') {
      inString = true;
      out += c;
    } else if (c === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      out += "\n";
    } else if (c === "/" && text[i + 1] === "*") {
      i = text.indexOf("*/", i + 2) + 1;
      if (i === 0) throw new Error("Unclosed comment in wrangler.jsonc");
    } else {
      out += c;
    }
  }
  return out.replace(/,(\s*[}\]])/g, "$1");
}

if (!existsSync(LOCAL)) {
  console.error(
    `${LOCAL} is missing. Copy wrangler.production.example.json to ${LOCAL} and fill in your values.`,
  );
  process.exit(1);
}
const shared = JSON.parse(stripJsonc(await readFile("wrangler.jsonc", "utf8")));
const local = JSON.parse(await readFile(LOCAL, "utf8"));

const missing = [];
if (!Array.isArray(local.routes) || local.routes.length === 0) missing.push("routes");
if (typeof local.database_id !== "string" || local.database_id === PLACEHOLDER)
  missing.push("database_id");
for (const name of ["PUBLIC_BASE_URL", "TELEGRAM_BOT_USERNAME"]) {
  if (typeof local.vars?.[name] !== "string" || local.vars[name] === "")
    missing.push(`vars.${name}`);
}
if (missing.length) {
  console.error(`${LOCAL} needs: ${missing.join(", ")}`);
  process.exit(1);
}

const production = {
  ...shared,
  $schema: undefined,
  routes: local.routes,
  vars: { ...shared.vars, ...local.vars },
  d1_databases: shared.d1_databases.map((db) =>
    db.binding === "DB" ? { ...db, database_id: local.database_id } : db,
  ),
};
delete production.$schema;
await writeFile(
  OUT,
  `// Generated by scripts/production-config.mjs from wrangler.jsonc and ${LOCAL}. Do not edit or commit.\n${JSON.stringify(production, null, 2)}\n`,
);
console.log(`Wrote ${OUT}`);
